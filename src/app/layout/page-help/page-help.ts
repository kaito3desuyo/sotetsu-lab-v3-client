/** URL からパスの型を作る。`;` `?` `#` 以降と末尾の `/` を取り除く（`/` だけは残す） */
export function toHelpPath(url: string): string {
    const path = url.split(/[;?#]/)[0];
    const trimmed = path.replace(/\/+$/, '');
    return trimmed === '' ? '/' : trimmed;
}

/** パスの型から説明を探す。表に無ければ投稿者ページか、null */
export function findPageHelp(path: string): PageHelp | null {
    const found = PAGE_HELP_TABLE[path];
    if (found) {
        return found;
    }
    if (path.startsWith('/moderation/users/')) {
        return MODERATION_USER;
    }
    return null;
}
